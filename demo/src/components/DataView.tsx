/** The Data tab: what is loaded in the browser and what the model calls it. */
import { useEffect, useState } from 'react'
import { DataGrid, type CubeModelMeta, type TableSpec } from '@spyglassjs/ui'
import { Database, Ruler, Sigma } from 'lucide-react'
import type { BrowserEngine } from '../engine/browserEngine'

const TABLES = ['orders', 'order_items', 'customers', 'products', 'traffic']

export function DataView({ engine, meta }: { engine: BrowserEngine; meta: CubeModelMeta }) {
  const [counts, setCounts] = useState<Record<string, number>>({})
  const [table, setTable] = useState('orders')
  const [sample, setSample] = useState<TableSpec | null>(null)

  useEffect(() => {
    void Promise.all(
      TABLES.map(async (t) => [t, Number((await engine.sql(`select count(*) as n from ${t}`))[0]?.n ?? 0)] as const),
    ).then((pairs) => setCounts(Object.fromEntries(pairs)))
  }, [engine])

  useEffect(() => {
    void engine.sql(`select * from ${table} order by 1 desc limit 12`).then((rows) => {
      const keys = Object.keys(rows[0] ?? {})
      setSample({
        type: 'table',
        // Arrow hands timestamps back as epoch milliseconds; show them as dates.
        columns: keys.map((k) => ({
          key: k,
          label: k,
          align: typeof rows[0]?.[k] === 'number' && !/_at$|^day$/.test(k) ? 'right' : 'left',
          ...(/_at$|^day$/.test(k) ? { format: 'date' as const } : {}),
        })),
        rows,
      })
    })
  }, [engine, table])

  return (
    <div className="mx-auto flex max-w-6xl flex-col gap-6 p-6">
      <section>
        <h2 className="mb-1 text-base font-semibold">Tables in this tab</h2>
        <p className="mb-3 text-sm text-muted-foreground">
          Generated by <code className="rounded bg-muted px-1 text-xs">seed.sql</code> inside DuckDB-WASM when the page loaded. Nothing leaves the browser.
        </p>
        <div className="grid grid-cols-5 gap-3">
          {TABLES.map((t) => (
            <button
              key={t}
              type="button"
              onClick={() => setTable(t)}
              className={`rounded-xl border bg-card p-3 text-left transition-colors ${table === t ? 'border-primary ring-2 ring-primary/15' : 'border-border hover:border-primary/40'}`}
            >
              <div className="flex items-center gap-2 text-sm font-medium">
                <Database className="h-3.5 w-3.5 text-muted-foreground" /> {t}
              </div>
              <div className="mt-1 text-xl font-semibold tabular-nums">{counts[t]?.toLocaleString() ?? '…'}</div>
              <div className="text-xs text-muted-foreground">rows</div>
            </button>
          ))}
        </div>
        {sample && (
          <div className="mt-3">
            <DataGrid spec={sample} />
          </div>
        )}
      </section>

      <section>
        <h2 className="mb-1 text-base font-semibold">The model</h2>
        <p className="mb-3 text-sm text-muted-foreground">
          <code className="rounded bg-muted px-1 text-xs">cubes.yml</code>, compiled by the spyglass engine running as WebAssembly. The analyst only ever sees these names.
        </p>
        <div className="grid grid-cols-2 gap-4">
          {meta.cubes.map((cube) => (
            <div key={cube.name} className="rounded-xl border border-border bg-card p-4">
              <div className="font-semibold">{cube.title ?? cube.name}</div>
              {cube.description && <div className="mt-0.5 text-sm text-muted-foreground">{cube.description}</div>}
              <div className="mt-3 flex flex-col gap-1.5">
                {cube.measures.map((m) => (
                  <div key={m.member} className="flex items-baseline gap-2 text-sm">
                    <Sigma className="h-3.5 w-3.5 shrink-0 translate-y-0.5 text-primary" />
                    <span className="font-medium">{m.title ?? m.name}</span>
                    {m.format && <span className="rounded bg-muted px-1.5 text-[11px] text-muted-foreground">{m.format}</span>}
                    {m.description && <span className="truncate text-xs text-muted-foreground">{m.description}</span>}
                  </div>
                ))}
                {cube.dimensions.map((d) => (
                  <div key={d.member} className="flex items-baseline gap-2 text-sm text-muted-foreground">
                    <Ruler className="h-3.5 w-3.5 shrink-0 translate-y-0.5" />
                    <span>{d.title ?? d.name}</span>
                    {d.type === 'time' && <span className="rounded bg-muted px-1.5 text-[11px]">time</span>}
                    {d.drill_entity && <span className="rounded bg-primary/10 px-1.5 text-[11px] text-primary">drills to {d.drill_entity}</span>}
                  </div>
                ))}
              </div>
            </div>
          ))}
        </div>
      </section>
    </div>
  )
}
